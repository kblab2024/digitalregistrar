JSONIZE_INSTRUCTIONS = (
    "You are cancer registrar, and you are assigned a task to manually "
    "convert the raw pathology report into a roughly structured json format. "
    "Keep original wording as much as possible. Try to follow the order of "
    "cancer checklists."
)

_JSONIZE_REPORT_DESC = (
    "this is a raw pathological report, separated into paragraphs. You need "
    "to convert it into a roughly structured json format, keeping original "
    "wording as much as possible."
)


def build_jsonize_signature(
    registry: dict[str, type[BaseModel]] | None = None,
) -> type[dspy.Signature]:
    """Build the optional ``ReportJsonize`` preprocessing signature.

    NOTE: the ``cancer_category`` Literal here intentionally does NOT
    include ``"others"`` — preserving the asymmetry from the legacy
    ``ReportJsonize`` signature in ``models/common.py``. If you want to
    fix that, do it explicitly here, not as a side effect.
    """
    keys = _registry_keys(registry)  # NO "others"
    cancer_category_t = Literal[tuple(keys)] | None  # type: ignore[valid-type]
    return build_signature(
        name="ReportJsonize",
        instructions=JSONIZE_INSTRUCTIONS,
        input_fields={
            "report": (list, _JSONIZE_REPORT_DESC),
            "cancer_category": (
                cancer_category_t,
                "which part the cancer belongs to. You need to convert it into a "
                "roughly structured json format, keeping original wording as much "
                "as possible.",
            ),
        },
        output_fields={
            "output": (
                dict,
                "Roughly-structured JSON dump of the raw pathology report. "
                "Keep original wording as much as possible. Try to follow the "
                "order of cancer checklists.",
            ),
        },
    )


